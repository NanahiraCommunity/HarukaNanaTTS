// Generates core/src/commonMain/kotlin/dev/nanatts/text/UnicodeData.kt: the Unicode normalisation tables used
// by dev.nanatts.text.Normalizer, extracted from the JDK running this program (so they match java.text.Normalizer).
//
// Run with: gradle :core:generateUnicodeData
// (or: java --add-exports java.base/jdk.internal.icu.text=ALL-UNNAMED \
//           --add-exports java.base/jdk.internal.icu.lang=ALL-UNNAMED core/tools/GenerateUnicodeData.java <out.kt>)
//
// The combining classes and decompositions come from the JDK's internal ICU copy; composition pairs are derived
// by splitting each primary composite and checked against java.text.Normalizer.

import java.io.IOException;
import java.lang.reflect.Method;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.text.Normalizer;
import java.util.ArrayList;
import java.util.List;

public class GenerateUnicodeData {

    private static final int HANGUL_FIRST = 0xAC00;
    private static final int HANGUL_LAST = 0xD7A3;
    /** Kotlin string constants are limited by the JVM class file format; stay well below it. */
    private static final int CHUNK = 16000;

    public static void main(String[] args) throws Exception {
        if (args.length != 1) {
            System.err.println("usage: java GenerateUnicodeData.java <out.kt>");
            System.exit(2);
        }
        Class<?> n2 = Class.forName("jdk.internal.icu.text.Normalizer2");
        Object nfd = n2.getMethod("getNFDInstance").invoke(null);
        Method combiningClass = n2.getMethod("getCombiningClass", int.class);

        StringBuilder ccc = new StringBuilder();
        StringBuilder canonical = new StringBuilder();
        StringBuilder compat = new StringBuilder();
        StringBuilder pairs = new StringBuilder();
        int counts[] = new int[4];
        for (int cp = 0; cp <= 0x10FFFF; cp++) {
            if (cp >= 0xD800 && cp <= 0xDFFF) {
                continue;
            }
            int cc = (Integer) combiningClass.invoke(nfd, cp);
            if (cc != 0) {
                entry(ccc, cp).append(Integer.toHexString(cc));
                counts[0]++;
            }
            if (cp >= HANGUL_FIRST && cp <= HANGUL_LAST) {
                continue; // algorithmic
            }
            String s = new String(Character.toChars(cp));
            String d = Normalizer.normalize(s, Normalizer.Form.NFD);
            String kd = Normalizer.normalize(s, Normalizer.Form.NFKD);
            if (!d.equals(s)) {
                hex(entry(canonical, cp), d);
                counts[1]++;
            }
            if (!kd.equals(d)) {
                hex(entry(compat, cp), kd);
                counts[2]++;
            }
            if (!d.equals(s) && Normalizer.normalize(d, Normalizer.Form.NFC).equals(s)) {
                int[] pair = splitComposite(d, s);
                if (pair == null) {
                    throw new IllegalStateException("cannot split composite U+" + Integer.toHexString(cp));
                }
                if (pair[1] >= 0) {
                    entry(pairs, cp).append(Integer.toHexString(pair[0])).append(' ').append(Integer.toHexString(pair[1]));
                    counts[3]++;
                }
            }
        }
        String version = "JDK " + Runtime.version().feature();

        StringBuilder out = new StringBuilder();
        out.append("// GENERATED by core/tools/GenerateUnicodeData.java from the Unicode data of ").append(version)
                .append(". Do not edit;\n// regenerate with: gradle :core:generateUnicodeData\n")
                .append("// Entries are ';'-separated, \"<hex code point>:<hex values separated by spaces>\".\n\n")
                .append("package dev.nanatts.text\n\n")
                .append("internal object UnicodeData {\n")
                .append("    const val SOURCE = \"").append(version).append("\"\n\n");
        table(out, "COMBINING_CLASSES", "canonical combining classes other than 0", ccc);
        table(out, "CANONICAL", "full canonical decompositions (NFD) that differ from the character", canonical);
        table(out, "COMPATIBILITY", "full compatibility decompositions (NFKD) that differ from the canonical one", compat);
        table(out, "COMPOSITIONS", "primary composites: composite to (first, second)", pairs);
        out.append("}\n");
        Files.writeString(Path.of(args[0]), out, StandardCharsets.UTF_8);
        System.out.printf("Unicode data of %s: %d combining classes, %d canonical, %d compatibility decompositions, %d compositions%n",
                version, counts[0], counts[1], counts[2], counts[3]);
    }

    /**
     * Finds (first, second) such that NFC(first + second) is the composite. Returns {first, -1} when the composite
     * is a singleton decomposition (never recomposed), null if no split works.
     */
    private static int[] splitComposite(String nfdOfComposite, String composite) {
        int[] d = nfdOfComposite.codePoints().toArray();
        for (int j = d.length - 1; j >= 1; j--) {
            StringBuilder rest = new StringBuilder();
            for (int i = 0; i < d.length; i++) {
                if (i != j) {
                    rest.appendCodePoint(d[i]);
                }
            }
            String first = Normalizer.normalize(rest, Normalizer.Form.NFC);
            if (first.codePointCount(0, first.length()) != 1) {
                continue;
            }
            String joined = first + new String(Character.toChars(d[j]));
            if (Normalizer.normalize(joined, Normalizer.Form.NFC).equals(composite)) {
                return new int[]{first.codePointAt(0), d[j]};
            }
        }
        return null;
    }

    private static StringBuilder entry(StringBuilder sb, int cp) {
        if (sb.length() > 0) {
            sb.append(';');
        }
        return sb.append(Integer.toHexString(cp)).append(':');
    }

    private static void hex(StringBuilder sb, String s) {
        boolean first = true;
        for (int cp : s.codePoints().toArray()) {
            if (!first) {
                sb.append(' ');
            }
            sb.append(Integer.toHexString(cp));
            first = false;
        }
    }

    private static void table(StringBuilder out, String name, String doc, StringBuilder data) {
        List<String> chunks = new ArrayList<>();
        int pos = 0;
        while (pos < data.length()) {
            int end = Math.min(data.length(), pos + CHUNK);
            if (end < data.length()) {
                end = data.lastIndexOf(";", end) + 1; // split between entries
            }
            chunks.add(data.substring(pos, end));
            pos = end;
        }
        out.append("    /** ").append(doc).append(" */\n");
        out.append("    val ").append(name).append(": Array<String> = arrayOf(\n");
        for (String c : chunks) {
            out.append("        \"").append(c).append("\",\n");
        }
        out.append("    )\n\n");
    }
}
